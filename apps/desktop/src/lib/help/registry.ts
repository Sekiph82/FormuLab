/**
 * Resolve the help topic for a real pathname (e.g. from `useLocation()`).
 * Two passes, most-specific first: an exact/parameterized match against
 * every "exact"-mode route (covers every real route in this app today —
 * `matchPath` itself handles `:param` segments, no hand-rolled parsing),
 * then a `mode: "prefix"` match — the parent-topic fallback a nested path
 * like `/settings/appearance` or `/live/<id>` needs when only its base
 * path (`/settings`, `/live`) is registered. A topic never matches a
 * route it doesn't list; there is no implicit "looks similar" fallback.
 */
export function topicForRoute(pathname: string): HelpTopic | undefined {
  for (const topic of HELP_TOPICS) {
    for (const route of topic.routes) {
      if (route.mode === "prefix") continue; // second pass only
      if (matchPath({ path: route.path, end: true }, pathname)) return topic;
    }
  }
  for (const topic of HELP_TOPICS) {
    for (const route of topic.routes) {
      if (route.mode === "prefix" && matchPath({ path: route.path, end: false }, pathname)) return topic;
    }
  }
  return undefined;
}

export function getTopic(id: string): HelpTopic | undefined {
  return HELP_TOPICS.find((t) => t.id === id);
}

export function relatedTopics(topic: HelpTopic): HelpTopic[] {
  return topic.relatedTopicIds.map(getTopic).filter((t): t is HelpTopic => t !== undefined);
}

export function isExcludedRoute(route: string): boolean {
  return HELP_EXCLUSIONS.some((e) => e.route === route);
}
