/** Routes deliberately given no help topic, with why — so "does this
 *  route have coverage" is always an explicit yes/no/excluded, never a
 *  silent gap. Every route in `router.tsx` must be covered by either
 *  `HELP_TOPICS` (directly or via `parentTopicId`/prefix fallback) or an
 *  entry here (checked by the registry test). */
